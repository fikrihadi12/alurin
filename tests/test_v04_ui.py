"""End-to-end tests for ALURIN v0.4. Uses a local HTTP server and Chromium."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
import json, os
BASE=Path(__file__).resolve().parents[1]
RESULT={'routes':{},'checks':{},'errors':[],'notes':[]}
HTML=(BASE/'index.html').read_text()
CSS=(BASE/'css/style.v0.4.css').read_text()
JS_FILES=['engine.v0.4.js','stage2-views.v0.4.js','adaptive-engine.v0.4.js','stage3-views.v0.4.js','app.v0.4.js']
def build_html(preload=None):
    html=HTML.replace('<link rel="stylesheet" href="css/style.v0.4.css">','')
    for name in JS_FILES:
        html=html.replace(f'<script src="js/{name}" defer></script>','')
    html=html.replace('</head>','<style>'+CSS+'</style></head>')
    state=json.dumps(preload or {},ensure_ascii=False)
    shim='''<script>(function(){const state=JSON.parse(STATE);Object.defineProperty(window,'localStorage',{configurable:true,value:{getItem:k=>Object.prototype.hasOwnProperty.call(state,k)?state[k]:null,setItem:(k,v)=>{state[k]=String(v)},removeItem:k=>delete state[k],clear:()=>Object.keys(state).forEach(k=>delete state[k]),key:i=>Object.keys(state)[i]||null,get length(){return Object.keys(state).length},__dump:()=>state}});})();</script>'''.replace('STATE',json.dumps(state))
    scripts=''.join('<script>'+ (BASE/'js'/name).read_text()+'</script>' for name in JS_FILES)
    return html.replace('</body>',shim+scripts+'</body>')
def check(name,ok,detail=''):
    RESULT['checks'][name]=bool(ok)
    if not ok: RESULT['notes'].append({'check':name,'detail':detail})
def login_student(page,name='Andi Pratama',class_name='X-1',attendance='12'):
    if page.locator('[data-form="student-login"]').count()==0:
        page.evaluate('location.hash="#/login"');page.wait_for_timeout(80)
    expect(page.locator('[data-form="student-login"]')).to_be_visible()
    page.wait_for_timeout(120)
    page.locator('[name="studentName"]').fill(name)
    page.locator('[name="className"]').fill(class_name)
    page.locator('[name="attendance"]').fill(attendance)
    page.locator('[data-form="student-login"] button[type="submit"]').click()
    page.wait_for_timeout(150)
    expect(page.locator('main h1')).to_contain_text('Halo')
def login_admin(page):
    if page.locator('[data-form="admin-login"]').count()==0:
        page.evaluate('location.hash="#/login"');page.wait_for_timeout(80)
    page.locator('[name="adminUser"]').fill('admin')
    page.locator('[name="adminPass"]').fill('alurin-demo')
    page.locator('[data-form="admin-login"] button[type="submit"]').click()
    page.wait_for_timeout(150)
    expect(page.locator('main h1')).to_contain_text('Dashboard Admin')
def route(page,key):
    page.evaluate('(k)=>location.hash="#/"+k',key)
    page.wait_for_timeout(80)
def correct_lab(page,scenario):
    page.locator('[data-lab-scenario]').select_option(scenario)
    page.locator('[data-lab-move="input"][data-dir="up"]').click()
    page.locator('[data-lab-shape="input"]').select_option('io')
    page.locator('[data-lab-shape="decision"]').select_option('decision')
    page.locator('[data-lab-tab="1"]').click()
    page.locator('[data-lab-branch="yes"]').select_option('yes')
    page.locator('[data-lab-branch="no"]').select_option('no')
    page.locator('[data-action="lab-check"]').click()
    expect(page.locator('.lab-feedback.good')).to_be_visible()

